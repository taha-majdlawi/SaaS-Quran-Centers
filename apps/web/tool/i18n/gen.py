# Generates src/lib/i18n/dictionaries/staff.ts (the admin / teacher dashboards'
# strings, t.staff.*) from the spec_*.py files next to this one:
#   python3 tool/i18n/gen.py        (from apps/web)
# Each spec row is (key, arabic, english): a string, a list or a map; placeholders
# like {name} are filled with fmt(). A language missing a key, a list of another
# length or a map with other keys fails here; TypeScript then checks that the
# English half has exactly the Arabic half's shape. See docs/I18N.md.
import glob, importlib.util, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = {}
for f in sorted(glob.glob(os.path.join(HERE, 'spec_*.py'))):
    s = importlib.util.spec_from_file_location(os.path.basename(f)[:-3], f); m = importlib.util.module_from_spec(s); s.loader.exec_module(m)
    for k, v in m.SPEC.items():
        assert k not in SPEC, k
        SPEC[k] = v

# Turkish and French: l10n/<lang>/<group>.py, each `T = {key: value}` with the
# same keys and shapes as the English column. A missing key fails the build.
EXTRA = ('tr', 'fr')
L10N = {}
for lang in EXTRA:
    L10N[lang] = {}
    for f in sorted(glob.glob(os.path.join(HERE, 'l10n', lang, '*.py'))):
        s = importlib.util.spec_from_file_location(f'{lang}_' + os.path.basename(f)[:-3], f); m = importlib.util.module_from_spec(s); s.loader.exec_module(m)
        L10N[lang][os.path.basename(f)[:-3]] = m.T

def check_l10n():
    problems = []
    for lang in EXTRA:
        for name, (doc, rows) in SPEC.items():
            t = L10N[lang].get(name)
            if t is None:
                problems.append(f'{lang}: group {name} missing'); continue
            keys = {r[0] for r in rows}
            for k in keys - set(t): problems.append(f'{lang}.{name}.{k} missing')
            for k in set(t) - keys: problems.append(f'{lang}.{name}.{k} is not in the spec')
            for key, ar, en in rows:
                if key not in t: continue
                v = t[key]
                if type(v) != type(en): problems.append(f'{lang}.{name}.{key}: wrong type'); continue
                if isinstance(en, dict) and set(v) != set(en): problems.append(f'{lang}.{name}.{key}: map keys differ')
                if isinstance(en, list) and len(v) != len(en): problems.append(f'{lang}.{name}.{key}: list length differs')
                # every {placeholder} of the English must survive
                import re
                flat = lambda x: ' '.join(x.values()) if isinstance(x, dict) else ' '.join(x) if isinstance(x, list) else x
                if set(re.findall(r'\{(\w+)\}', flat(en))) != set(re.findall(r'\{(\w+)\}', flat(v))):
                    problems.append(f'{lang}.{name}.{key}: placeholders differ')
    if problems:
        raise SystemExit('translations incomplete:\n  ' + '\n  '.join(problems[:60]) + (f'\n  ... {len(problems) - 60} more' if len(problems) > 60 else ''))

check_l10n()

def lit(v, ind):
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"
    if isinstance(v, list):
        return '[' + ', '.join(lit(x, ind) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join(f'{json.dumps(str(k))}: {lit(x, ind)}' for k, x in v.items()) + ' } as Record<string, string>'
    raise TypeError(v)

def block(li):
    out = []
    for name, (doc, rows) in SPEC.items():
        if isinstance(li, str):
            out.append(f'  /** {doc} */')
            out.append(f'  {name}: {{')
            for row in rows:
                out.append(f'    {row[0]}: {lit(L10N[li][name][row[0]], 4)},')
            out.append('  },')
            continue
        out.append(f'  /** {doc} */')
        out.append(f'  {name}: {{')
        seen = set()
        for row in rows:
            key, ar, en = row
            assert key not in seen, (name, key); seen.add(key)
            assert type(ar) == type(en), (name, key)
            if isinstance(ar, dict): assert set(ar) == set(en), (name, key)
            if isinstance(ar, list): assert len(ar) == len(en), (name, key)
            out.append(f'    {key}: {lit(row[li], 4)},')
        out.append('  },')
    return '\n'.join(out)

HEADER = """// GENERATED by tool/i18n/gen.py from tool/i18n/spec_*.py - edit the spec, not this file.
// The admin / teacher dashboards' strings, reached as t.staff.* . One file per
// language: the server loads only the language of the request (lib/i18n/server.ts).
"""
DIR = os.path.join(HERE, '..', '..', 'src', 'lib', 'i18n', 'dictionaries')
open(os.path.join(DIR, 'staff.ar.ts'), 'w').write(HEADER + f"""
export const staffAr = {{
{block(1)}
}};
""")
for code, name, li in (('en', 'staffEn', 2), ('tr', 'staffTr', 'tr'), ('fr', 'staffFr', 'fr')):
    open(os.path.join(DIR, f'staff.{code}.ts'), 'w').write(HEADER + f"""
import type {{ staffAr }} from './staff.ar';

export const {name}: typeof staffAr = {{
{block(li)}
}};
""")
print('generated', sum(len(r) for _, r in SPEC.values()), 'strings in', len(SPEC), 'groups')
