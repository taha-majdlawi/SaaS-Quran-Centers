# Generates src/lib/i18n/dictionaries/staff.ts (the admin / teacher dashboards'
# strings, t.staff.*) from the spec_*.py files next to this one:
#   python3 tool/i18n/gen.py        (from apps/web)
# Each spec row is (key, arabic, english): a string, a list or a map; placeholders
# like {name} are filled with fmt(). A language missing a key, a list of another
# length or a map with other keys fails here; TypeScript then checks that the
# English half has exactly the Arabic half's shape. See docs/I18N.md.
import glob, importlib.util, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = {}
for f in sorted(glob.glob(os.path.join(HERE, 'spec_*.py'))):
    s = importlib.util.spec_from_file_location(os.path.basename(f)[:-3], f); m = importlib.util.module_from_spec(s); s.loader.exec_module(m)
    for k, v in m.SPEC.items():
        assert k not in SPEC, k
        SPEC[k] = v

def lit(v, ind):
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"
    if isinstance(v, list):
        return '[' + ', '.join(lit(x, ind) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join(f'{json.dumps(str(k))}: {lit(x, ind)}' for k, x in v.items()) + ' } as Record<string, string>'
    raise TypeError(v)

def block(li):
    out = []
    for name, (doc, rows) in SPEC.items():
        out.append(f'  /** {doc} */')
        out.append(f'  {name}: {{')
        seen = set()
        for row in rows:
            key, ar, en = row
            assert key not in seen, (name, key); seen.add(key)
            assert type(ar) == type(en), (name, key)
            if isinstance(ar, dict): assert set(ar) == set(en), (name, key)
            if isinstance(ar, list): assert len(ar) == len(en), (name, key)
            out.append(f'    {key}: {lit(row[li], 4)},')
        out.append('  },')
    return '\n'.join(out)

src = f"""// GENERATED by tool/i18n/gen.py from tool/i18n/spec_*.py - edit the spec, not this file.
// The admin / teacher dashboards' strings (phase 3), reached as t.staff.* .

export const staffAr = {{
{block(1)}
}};

export const staffEn: typeof staffAr = {{
{block(2)}
}};
"""
open(os.path.join(HERE, '..', '..', 'src', 'lib', 'i18n', 'dictionaries', 'staff.ts'), 'w').write(src)
print('generated', sum(len(r) for _, r in SPEC.values()), 'strings in', len(SPEC), 'groups')
